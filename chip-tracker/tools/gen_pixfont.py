"""The tracker's pixel fonts as a C header (app/pixfont.h), from fm1-base's Terminus BDFs (SIL OFL 1.1):
PF12 (Terminus 12 medium, 6 x 12) and PF16 (Terminus 16 bold, 8 x 16), characters 32..126, a byte a row
(bit 7 the left pixel). Run from the project's root: python3 tools/gen_pixfont.py"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "base" / "assets" / "fonts"


def glyphs(path):
    lines = path.read_text(errors="replace").splitlines()
    fbb = next(l for l in lines if l.startswith("FONTBOUNDINGBOX")).split()
    cw, ch, fy = int(fbb[1]), int(fbb[2]), int(fbb[4])
    base = ch + fy
    out = {}
    i = 0
    while i < len(lines):
        if lines[i].startswith("ENCODING"):
            code = int(lines[i].split()[1])
            j = i
            while not lines[j].startswith("BBX"):
                j += 1
            bw, bh, bx, by = map(int, lines[j].split()[1:5])
            k = j
            while not lines[k].startswith("BITMAP"):
                k += 1
            rows = [int(r, 16) for r in lines[k + 1:k + 1 + bh]]
            nbits = ((bw + 7) // 8) * 8
            cell = [0] * ch
            top = base - (by + bh)
            for r, bits in enumerate(rows):
                v = 0
                for c in range(bw):
                    if bits >> (nbits - 1 - c) & 1 and 0 <= bx + c < 8:
                        v |= 0x80 >> (bx + c)
                if 0 <= top + r < ch:
                    cell[top + r] = v
            out[code] = cell
            i = k + bh
        i += 1
    return cw, ch, out


def emit(name, path):
    cw, ch, g = glyphs(path)
    s = [f"#define {name}_W {cw}\n#define {name}_H {ch}\nstatic const uint8_t {name}[95][{ch}] = {{"]
    for c in range(32, 127):
        rows = g.get(c, g[ord("?")])
        s.append("    {" + ", ".join(f"0x{v:02X}" for v in rows) + "},   /* " + (repr(chr(c)) if c != 92 else "backslash") + " */")
    s.append("};\n")
    return "\n".join(s)


hdr = ["/* SPDX-License-Identifier: MPL-2.0 (the code); the glyphs are Terminus, (C) Dimitar Toshkov Zhekov, SIL OFL 1.1",
       " * Generated by tools/gen_pixfont.py from base/assets/fonts: do not edit. */",
       "#pragma once", "#include <stdint.h>", ""]
hdr.append(emit("PF12", FONTS / "ter-u12n.bdf"))
hdr.append(emit("PF16", FONTS / "ter-u16b.bdf"))
(ROOT / "app" / "pixfont.h").write_text("\n".join(hdr), newline="\n")
print("app/pixfont.h written")
